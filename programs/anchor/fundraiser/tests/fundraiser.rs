/// Fetch validity proof for vault creation, send `initialize` instruction.
async fn initialize<R: Rpc + TestRpc + Indexer>(
    rpc: &mut R,
    ctx: &FundraiserTestContext,
) {
    // Validity proof: verifies that the vault PDA's derived address does not
    // yet exist in Light's address tree.
    let proof_result = get_create_accounts_proof(
        rpc,
        &ctx.program_id,
        vec![CreateAccountsProofInput::pda(ctx.vault_pda)],
    )
    .await
    .unwrap();

    let accounts = fundraiser::accounts::Initialize {
        fee_payer: ctx.maker.pubkey(),
        authority: ctx.authority_pda,
        mint_to_raise: ctx.mint_pubkey,
        fundraiser: ctx.fundraiser_pda,
        vault: ctx.vault_pda,
        token_program: ctx.token_config.token_program_id(),
        system_program: solana_sdk::system_program::ID,
        light_token_program: Pubkey::new_from_array(LIGHT_TOKEN_PROGRAM_ID),
        light_token_config: COMPRESSIBLE_CONFIG_V1,
        light_token_rent_sponsor: RENT_SPONSOR,
        light_token_cpi_authority: CPI_AUTHORITY_PDA,
    };

    let data = fundraiser::instruction::Initialize {
        params: fundraiser::instructions::InitializeParams {
            create_accounts_proof: proof_result.create_accounts_proof,
            amount: ctx.amount_to_raise,
            duration: ctx.duration,
            vault_bump: ctx.vault_bump,
        },
    };

    // Remaining accounts: Light system accounts for proof verification
    // and address tree insertion (see `get_create_accounts_proof`).
    let ix = Instruction {
        program_id: ctx.program_id,
        accounts: [
            accounts.to_account_metas(None),
            proof_result.remaining_accounts,
        ]
        .concat(),
        data: data.data(),
    };

    rpc.create_and_send_transaction(
        &[ix],
        &ctx.payer.pubkey(),
        &[&ctx.payer, &ctx.maker],
    )
    .await
    .expect("initialize should succeed");
}

/// Send `contribute` instruction: contributor transfers tokens into the vault.
async fn contribute<R: Rpc + TestRpc + Indexer>(
    rpc: &mut R,
    ctx: &FundraiserTestContext,
    contributor: &Keypair,
    contributor_ata: Pubkey,
    amount: u64,
) {
    let (contributor_account_pda, _) = Pubkey::find_program_address(
        &[
            b"contributor",
            ctx.fundraiser_pda.as_ref(),
            contributor.pubkey().as_ref(),
        ],
        &ctx.program_id,
    );

    let accounts = fundraiser::accounts::Contribute {
        contributor: contributor.pubkey(),
        mint_to_raise: ctx.mint_pubkey,
        fundraiser: ctx.fundraiser_pda,
        contributor_account: contributor_account_pda,
        contributor_ata,
        vault: ctx.vault_pda,
        token_program: ctx.token_config.token_program_id(),
        system_program: solana_sdk::system_program::ID,
        light_token_program: Pubkey::new_from_array(LIGHT_TOKEN_PROGRAM_ID),
        light_token_rent_sponsor: RENT_SPONSOR,
        light_token_cpi_authority: CPI_AUTHORITY_PDA,
        spl_interface_pda: ctx
            .spl_interface
            .as_ref()
            .map(|i| i.pda)
            .unwrap_or_default(),
    };

    let (_, spl_interface_bump) = find_spl_interface_pda(&ctx.mint_pubkey, false);
    let data = fundraiser::instruction::Contribute { amount, spl_interface_bump };

    let ix = Instruction {
        program_id: ctx.program_id,
        accounts: accounts.to_account_metas(None),
        data: data.data(),
    };

    rpc.create_and_send_transaction(
        &[ix],
        &ctx.payer.pubkey(),
        &[&ctx.payer, contributor],
    )
    .await
    .expect("contribute should succeed");
}

/// Create maker's token account, send `check_contributions` instruction to claim funds.
///
/// Returns the maker's ATA pubkey.
async fn check_contributions<R: Rpc + TestRpc + Indexer>(
    rpc: &mut R,
    ctx: &FundraiserTestContext,
) -> Pubkey {
    let maker_ata = match ctx.token_config {
        TokenConfig::Spl | TokenConfig::LightSpl => {
            create_spl_ata(rpc, &ctx.payer, &ctx.mint_pubkey, &ctx.maker.pubkey()).await
        }
        TokenConfig::Token2022 | TokenConfig::LightT22 => {
            create_t22_ata(rpc, &ctx.payer, &ctx.mint_pubkey, &ctx.maker.pubkey()).await
        }
        TokenConfig::Light => {
            create_light_ata(rpc, &ctx.payer, &ctx.mint_pubkey, &ctx.maker.pubkey()).await
        }
    };

    let accounts = fundraiser::accounts::CheckContributions {
        fee_payer: ctx.maker.pubkey(),
        authority: ctx.authority_pda,
        mint_to_raise: ctx.mint_pubkey,
        fundraiser: ctx.fundraiser_pda,
        vault: ctx.vault_pda,
        maker_ata,
        token_program: ctx.token_config.token_program_id(),
        system_program: solana_sdk::system_program::ID,
        light_token_program: Pubkey::new_from_array(LIGHT_TOKEN_PROGRAM_ID),
        light_token_rent_sponsor: RENT_SPONSOR,
        light_token_cpi_authority: CPI_AUTHORITY_PDA,
        spl_interface_pda: ctx
            .spl_interface
            .as_ref()
            .map(|i| i.pda)
            .unwrap_or_default(),
    };

    let (_, spl_interface_bump) = find_spl_interface_pda(&ctx.mint_pubkey, false);
    let data = fundraiser::instruction::CheckContributions { spl_interface_bump };

    let ix = Instruction {
        program_id: ctx.program_id,
        accounts: accounts.to_account_metas(None),
        data: data.data(),
    };

    rpc.create_and_send_transaction(
        &[ix],
        &ctx.payer.pubkey(),
        &[&ctx.payer, &ctx.maker],
    )
    .await
    .expect("check_contributions should succeed");

    maker_ata
}

