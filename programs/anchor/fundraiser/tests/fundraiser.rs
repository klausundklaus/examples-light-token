//! Light Token fundraiser: crowdfunding with rent-free vault.
//!
//! This test shows fundraiser patterns adapted for Light Token.
//!
//! 1. **Authority PDA owns the vault** — not the fundraiser account. This lets
//!    the authority sign vault withdrawals without needing account data
//!    (see `initialize.rs` `#[light_account(init, token::owner = authority)]`).
//!
//! 2. **Vault is rent-free** — it's a Light Token account sponsored by
//!    `RENT_SPONSOR`, eliminating the ~0.002 SOL rent per fundraiser.
//!
//! 3. **Validity proof for account creation** — `get_create_accounts_proof()`
//!    fetches a validity proof that the vault PDA's derived address does not
//!    yet exist in Light's address tree. Only needed in `initialize` (creating
//!    new state); `contribute`, `check_contributions`, and `refund` read
//!    existing accounts and need no proof.
//!
//! ## Token scenarios
//!
//! The vault is always a Light Token account. The contributor's account type
//! determines which CPI path `TransferInterfaceCpi` selects:
//!
//! | Test | Mint | Contributor accounts | Transfer path | Purpose |
//! |------|------|---------------------|---------------|---------|
//! | `test_fundraiser_spl` | SPL | SPL associated token accounts | `TransferInterfaceCpi` | SPL mints work with Light vault |
//! | `test_fundraiser_t22` | Token 2022 | Token 2022 associated token accounts | `TransferInterfaceCpi` | Token 2022 mints work with Light vault |
//! | `test_fundraiser_light` | Light | Associated Light Token accounts | `TransferCheckedCpi` | Rent-free path |
//! | `test_fundraiser_spl_light` | SPL | Associated Light Token accounts | `TransferCheckedCpi` | SPL mint, converted contributor accounts |
//! | `test_fundraiser_t22_light` | Token 2022 | Associated Light Token accounts | `TransferCheckedCpi` | Token 2022 mint, converted contributor accounts |
//!
//! For `Spl`/`Token2022`: contributor accounts are SPL/Token 2022, vault is Light →
//! `TransferInterfaceCpi` (with SPL interface PDA).
//!
//! For `Light`/`LightSpl`/`LightT22`: all accounts are Light Token →
//! `TransferCheckedCpi` (no interface PDA needed).
//!
//! `LightSpl`/`LightT22` convert tokens from SPL/Token 2022 associated token accounts
//! into associated Light Token accounts *before* the fundraiser starts (in `create_contributor`).
//! The fundraiser itself only sees Light Token accounts.
//!
//! ## Cold/hot lifecycle
//!
//! The vault is a PDA-owned Light Token account that turns cold when
//! sponsored rent expires. Loading a cold vault back to active requires
//! `VaultSeeds` / `LightAccountVariant::Vault` (generated by `#[light_program]`
//! when state derives `LightAccount`). Since `Fundraiser` uses standard
//! `#[account]`, these types aren't generated, so the test doesn't exercise
//! cold/hot lifecycle. See the escrow tests for full cold/hot coverage.

