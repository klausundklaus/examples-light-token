/// Run the fundraiser refund flow: deadline passes, target not met, contributors reclaim.
///
/// 1. Initialize fundraiser with short duration (1 day)
/// 2. 3 contributors each contribute 10% (30% total — target not met)
/// 3. Advance clock past deadline (set unix_timestamp directly — no slot warp)
/// 4. Each contributor calls refund to reclaim tokens
/// 5. Verify vault empty, contributor balances restored, fundraiser still exists
async fn run_fundraiser_refund_flow(
    rpc: &mut LightProgramTest,
    ctx: &FundraiserTestContext,
) {
    initialize(rpc, ctx).await;

    verify_light_token_balance(rpc, ctx.vault_pda, 0, "vault (initial)").await;

    let contribution_amount = ctx.amount_to_raise * 10 / 100;
    let contributor_funding = contribution_amount * 2;
    let num_contributors = 3;

    let mut contributors: Vec<(Keypair, Pubkey)> = Vec::new();
    for _i in 0..num_contributors {
        let (contributor, contributor_ata) =
            create_contributor(rpc, ctx, contributor_funding).await;
        contribute(rpc, ctx, &contributor, contributor_ata, contribution_amount).await;
        contributors.push((contributor, contributor_ata));
    }

    let total_contributed = contribution_amount * num_contributors as u64;
    verify_light_token_balance(rpc, ctx.vault_pda, total_contributed, "vault (partial)").await;

    // Advance the Clock sysvar's unix_timestamp directly — `warp_epoch_forward`
    // only updates the slot, not unix_timestamp, in LiteSVM.
    //
    // We don't warp slots here because `warp_epoch_forward` turns all Light
    // accounts cold (vault, mints, contributor token accounts), and the fundraiser can't load
    // the vault from cold: `Fundraiser` doesn't derive `LightAccount`, so
    // `#[light_program]` doesn't generate `VaultSeeds` / `LightAccountVariant::Vault`
    // needed by `create_load_instructions`.
    //
    // Duration is 1 day. Refund requires `duration < elapsed_days`, so we need
    // the elapsed time to exceed 1 full day (86,400 seconds). Use 2 days.
    {
        use solana_sdk::clock::Clock;
        let mut clock = rpc.context.get_sysvar::<Clock>();
        clock.unix_timestamp += 2 * 86_400; // advance 2 days
        rpc.context.set_sysvar(&clock);
    }

    for (contributor, contributor_ata) in &contributors {
        refund(rpc, ctx, contributor, *contributor_ata).await;

        // Verify contributor received tokens back (started with contributor_funding,
        // contributed contribution_amount, got it back → net = contributor_funding)
        verify_light_token_balance(
            rpc,
            *contributor_ata,
            contributor_funding,
            "contributor_ata (after refund)",
        )
        .await;

        let (contributor_account_pda, _) = Pubkey::find_program_address(
            &[
                b"contributor",
                ctx.fundraiser_pda.as_ref(),
                contributor.pubkey().as_ref(),
            ],
            &ctx.program_id,
        );
        let contributor_acct = rpc.get_account(contributor_account_pda).await.unwrap();
        assert!(
            contributor_acct.is_none(),
            "Contributor account should be closed after refund"
        );
    }

    verify_light_token_balance(rpc, ctx.vault_pda, 0, "vault (after all refunds)").await;

    let fundraiser_account = rpc.get_account(ctx.fundraiser_pda).await.unwrap();
    assert!(
        fundraiser_account.is_some(),
        "Fundraiser account should still exist after refunds (only closed by check_contributions)"
    );
}

