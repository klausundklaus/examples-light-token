/// Run the full fundraiser claim flow for any token configuration: SPL, Token 2022, Light.
///
/// 1. Initialize fundraiser: create vault, record terms
/// 2. Verify vault has 0 balance
/// 3. 10 contributors each contribute 10% of target
/// 4. Verify vault reached target
/// 5. Maker claims funds via check_contributions
/// 6. Verify final balances and account closure
async fn run_fundraiser_full_flow<R: Rpc + TestRpc + Indexer>(
    rpc: &mut R,
    ctx: &FundraiserTestContext,
) {
    initialize(rpc, ctx).await;

    verify_light_token_balance(rpc, ctx.vault_pda, 0, "vault (initial)").await;

    let contribution_amount = ctx.amount_to_raise * 10 / 100;
    let contributor_funding = contribution_amount * 2; // extra for fees

    for _i in 0..10 {
        let (contributor, contributor_ata) =
            create_contributor(rpc, ctx, contributor_funding).await;
        contribute(rpc, ctx, &contributor, contributor_ata, contribution_amount).await;
    }

    verify_light_token_balance(
        rpc,
        ctx.vault_pda,
        ctx.amount_to_raise,
        "vault (target reached)",
    )
    .await;

    let maker_ata = check_contributions(rpc, ctx).await;

    verify_light_token_balance(rpc, ctx.vault_pda, 0, "vault (after claim)").await;

    verify_light_token_balance(
        rpc,
        maker_ata,
        ctx.amount_to_raise,
        "maker_ata (after claim)",
    )
    .await;

    let fundraiser_account = rpc.get_account(ctx.fundraiser_pda).await.unwrap();
    assert!(
        fundraiser_account.is_none(),
        "Fundraiser account should be closed after check_contributions"
    );
}

